# Add or check the SPDX license header that source files start with.
#
#   scripts/license-headers.sh add   [file...]   add the header where it is missing
#   scripts/license-headers.sh check [file...]   list files without it; exit 1 if any
#
# With no files, it covers every file Git tracks. The header text is in
# .github/license-header.tmpl. addlicense picks the comment syntax from the file
# type and skips the types it has none for, such as JSON and Markdown.
#
# `make license`, `make license-check`, the pre-commit hook and the License
# Headers workflow all call this script, so they all cover the same files.

set -euo pipefail

ADDLICENSE="github.com/google/addlicense@v1.2.0"
TEMPLATE=".github/license-header.tmpl"

# Files that never get a header.
IGNORE=(
    'portals/apps/admin/**'  # paused prototypes, which AGENTS.md says not to change
    'portals/apps/member/**'
    '**/pnpm-lock.yaml'      # generated by pnpm
    '**/testdata/**'         # test fixtures
    '**/node_modules/**'
    '**/dist/**'
)

usage() {
    echo "usage: $0 add|check [file...]" >&2
    exit 2
}

[ "$#" -ge 1 ] || usage
MODE="$1"
shift
case "$MODE" in
add) FLAGS=() ;;
check) FLAGS=(-check) ;;
*) usage ;;
esac

# Work from the repository root, so the ignore patterns match. File arguments
# are relative to the caller's directory; make them relative to the root.
ROOT="$(git rev-parse --show-toplevel)"
PREFIX="$(git rev-parse --show-prefix)"
FILES=()
for f in "$@"; do
    case "$f" in
    "$ROOT"/*) FILES+=("${f#"$ROOT"/}") ;;
    /*) FILES+=("$f") ;;
    *) FILES+=("$PREFIX$f") ;;
    esac
done
cd "$ROOT"
if [ "$#" -eq 0 ]; then
    while IFS= read -r -d '' f; do FILES+=("$f"); done < <(git ls-files -z)
fi
[ "${#FILES[@]}" -gt 0 ] || exit 0

FLAGS+=(-f "$TEMPLATE")
for pattern in "${IGNORE[@]}"; do
    FLAGS+=(-ignore "$pattern")
done

status=0
go run "$ADDLICENSE" "${FLAGS[@]}" "${FILES[@]}" || status=$?
if [ "$status" -ne 0 ] && [ "$MODE" = check ]; then
    echo "The files above have no license header. Add it with: make license" >&2
fi
exit "$status"
